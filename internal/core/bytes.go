// Package core — ядро программы: общие понятия (размер, объект, категория,
// действие, провайдер) и правила, которые к ним применяются.
//
// core не импортирует ничего из проекта. Все остальные пакеты зависят
// от него, а не наоборот, поэтому ядро можно тестировать без интерфейса,
// без диска и без внешних программ.
package core

import "fmt"

// Bytes — размер в байтах. Отдельный тип вместо голого int64
// (value object): компилятор не даст случайно сложить байты
// с чем-то другим, а форматирование живёт в самом типе.
type Bytes int64

// String превращает размер в текст вроде "104.3 GB".
// fmt вызывает этот метод сам, когда печатает Bytes через %s, %v или Println.
// Делим на 1000, как Finder, а не на 1024, как df -h.
//
// (b Bytes) перед именем — «получатель»: метод принадлежит типу Bytes
// и вызывается как size.String().
func (b Bytes) String() string {
	const unit = 1000

	if b < unit {
		// int64(b) — явно превращаем обратно в число, чтобы
		// fmt не пытался вызвать String() у Bytes по кругу.
		return fmt.Sprintf("%d B", int64(b))
	}

	units := []string{"kB", "MB", "GB", "TB", "PB"} // срез строк, как массив в JS
	value := float64(b) / unit                      // дробное число, чтобы было 1.5, а не 1
	i := 0

	// В Go есть только for, отдельного while нет. Это и есть «while»:
	// делим, пока число не меньше 1000 и есть следующая единица.
	for value >= unit && i < len(units)-1 {
		value /= unit
		i++
	}

	// %.1f — дробное число с одним знаком после точки.
	return fmt.Sprintf("%.1f %s", value, units[i])
}
